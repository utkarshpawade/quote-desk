/**
 * Intake eval: runs the synthetic RFQ emails in tests/fixtures/intake-eval.ts through the same
 * reading, grounding, confidence and merge code as the app, and writes docs/intake-eval.md.
 *   npm run eval:intake            rule-based reading, plus the AI when GROQ_API_KEY is set
 */
import { writeFileSync } from "node:fs";
import { todayIst } from "../src/domain/calendar";
import { proposalsFor, readCaseByRules, scoreCase, summarize, emailText, type EvalCase, type FieldResult } from "../src/domain/intake/eval";
import type { MaterialOption } from "../src/domain/intake/normalize";
import { aiConfig } from "../src/server/ai/groq";
import { extractWithAi, PROMPT_VERSION } from "../src/server/ai/extract";
import { SEED_ITEMS } from "../src/server/seed/catalog";
import { EVAL_CASES, RECEIVED } from "../tests/fixtures/intake-eval";

const materials: MaterialOption[] = SEED_ITEMS.filter((i) => i.category === "MATERIAL").map((i) => ({
  id: i.code,
  grade: String(i.attributes?.grade),
  aliases: (i.attributes?.aliases as string[] | undefined) ?? [],
}));
const ctx = { materials, receivedDate: RECEIVED };

type Run = { name: string; results: FieldResult[]; failures: string[]; ms: number };

async function run(name: string, read: (c: EvalCase) => Promise<FieldResult[]>): Promise<Run> {
  const results: FieldResult[] = [];
  const failures: string[] = [];
  const started = Date.now();
  for (const c of EVAL_CASES) {
    try {
      results.push(...(await read(c)));
    } catch (error) {
      failures.push(`${c.id}: ${(error as Error).message}`);
    }
  }
  return { name, results, failures, ms: Date.now() - started };
}

const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)} %` : "—");
const show = (v: string | number | null) => (v === null ? "—" : String(v));

function report(runs: Run[], aiSkipped: boolean): string {
  const lines: string[] = [];
  lines.push("# Intake eval", "");
  lines.push(
    `Generated by \`npm run eval:intake\` on ${todayIst()} over ${EVAL_CASES.length} synthetic RFQ emails (tests/fixtures/intake-eval.ts), read as if received on ${RECEIVED}. Prompt version \`${PROMPT_VERSION}\`.`,
    "",
    "Each case lists what a careful estimator would take from the email. Every field is scored through the same reading, grounding, confidence and merge code as the app:",
    "",
    "- **correct** — the right value is filled in;",
    "- **flagged** — wrong or unsure, but shown as Low, as a conflict, or left for the estimator;",
    "- **silent** — a wrong value filled in at Medium or High: the failure that can reach a quote;",
    "- **missed** — nothing read; the estimator types it;",
    "- **held / invented** — for values the email does not give: correctly left empty, or filled in anyway at Medium or High.",
    "",
    "| Reader | Fields | Correct | Flagged | Silent | Missed | Held back (of absent) | Invented | Time |",
    "|---|---|---|---|---|---|---|---|---|",
  );
  for (const r of runs) {
    const s = summarize(r.results);
    lines.push(
      `| ${r.name} | ${s.fields} | ${s.correct} (${pct(s.correct, s.fields)}) | ${s.flagged} | **${s.silent}** | ${s.missed} | ${s.held} of ${s.absent} | **${s.invented}** | ${(r.ms / 1000).toFixed(1)} s |`,
    );
  }
  if (aiSkipped) lines.push("", "_The AI reader was not run: GROQ_API_KEY was not set when this report was generated._");
  for (const r of runs) {
    lines.push("", `## ${r.name}`, "");
    if (r.failures.length) lines.push(...r.failures.map((f) => `- Failed: ${f}`), "");
    lines.push("| Case | Correct | Flagged | Silent | Missed | Invented |", "|---|---|---|---|---|---|");
    for (const c of EVAL_CASES) {
      const s = summarize(r.results.filter((x) => x.caseId === c.id));
      lines.push(`| ${c.id} — ${c.title} | ${s.correct}/${s.fields} | ${s.flagged} | ${s.silent} | ${s.missed} | ${s.invented} |`);
    }
    const notable = r.results.filter((x) => x.outcome === "silent" || x.outcome === "invented" || x.outcome === "flagged");
    if (notable.length) {
      lines.push("", "Not filled in correctly (excluding plain misses):", "", "| Case | Field | Expected | Read | Confidence | Outcome |", "|---|---|---|---|---|---|");
      for (const x of notable) {
        lines.push(`| ${x.caseId}${x.part !== null ? ` part ${x.part + 1}` : ""} | ${x.field} | ${show(x.expected)} | ${show(x.proposed)} | ${x.confidence ?? "—"} | ${x.outcome} |`);
      }
    }
  }
  return `${lines.join("\n")}\n`;
}

async function main() {
  const runs: Run[] = [await run("Rule-based reading", async (c) => scoreCase(c, readCaseByRules(c, ctx)))];
  const { apiKey, textModel } = aiConfig();
  if (apiKey) {
    runs.push(
      await run(`AI (${textModel})`, async (c) => {
        const { values } = await extractWithAi({ label: c.title, text: emailText(c) });
        return scoreCase(c, proposalsFor(c, values, "AI", ctx));
      }),
    );
  } else {
    console.log("GROQ_API_KEY is not set: only the rule-based reader is evaluated.");
  }
  const md = report(runs, !apiKey);
  writeFileSync("docs/intake-eval.md", md);
  for (const r of runs) {
    const s = summarize(r.results);
    console.log(`${r.name}: ${s.correct}/${s.fields} correct, ${s.flagged} flagged, ${s.silent} silent, ${s.missed} missed, ${s.invented} invented${r.failures.length ? `, ${r.failures.length} failed` : ""}`);
  }
  console.log("Wrote docs/intake-eval.md");
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
